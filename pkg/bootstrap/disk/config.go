package disk

import (
	"fmt"
	"strings"

	"github.com/oxidecomputer/karpenter-provider-oxide/pkg/apis/v1alpha1"
	"github.com/oxidecomputer/karpenter-provider-oxide/pkg/providers/storage"
)

// Table and fstab field values that stand for "this does not apply here".
const (
	// fieldNone is the placeholder for an empty mount point or block link, and for the filesystem of
	// a disk that arrives already carrying one.
	fieldNone = "-"
	// fieldRawBlock is what v1alpha1.FilesystemNone becomes: a disk that is linked, never formatted
	// and never mounted. Distinct from fieldNone so that "no filesystem was asked for" and "a raw
	// block device was asked for" stay different answers.
	fieldRawBlock = "none"
	// fstabAuto is the fstab filesystem type for a disk created from an image or a snapshot. What it
	// carries is a property of the source rather than of the nodeclass, so there is nothing to name
	// here and blkid is left to work it out at mount time.
	fstabAuto = "auto"
)

// mountOptions are the options every managed fstab entry carries.
//
// x-systemd.requires= is what orders the mount after the unit that formats the disk: it configures
// both a Requires= and an After= on the generated mount unit, which is the whole of the ordering
// guarantee and the reason no part of it has to be reasoned about in shell.
//
// nofail is deliberately absent. A node that boots with an empty directory where a data disk belongs
// is the exact failure this exists to prevent: without nofail the .mount unit fails, the consumer's
// RequiresMountsFor keeps it down, and the NodeClaim times out registering and is replaced.
const mountOptions = "defaults,noatime" +
	",x-systemd.requires=" + UnitName +
	",x-systemd.device-timeout=60s"

// DeviceName is the stable name udev gives one disk, and the only handle anything on the node needs.
//
// A diskSet name is unique within a nodeclass and an ordinal is unique within a set, so the pair is
// unique across a launch. It is derivable from the nodeclass alone, which is why the node writes no
// manifest: "which device is my disk" is answered by the path itself.
func DeviceName(setName string, ordinal int32) string {
	return fmt.Sprintf("%s-%d", setName, ordinal)
}

// DevicePath is where DeviceName lands under /dev.
func DevicePath(setName string, ordinal int32) string {
	return DeviceDir + "/" + DeviceName(setName, ordinal)
}

// UdevRules renders the rule file that gives every data disk a stable name.
//
// Matching is on the Identify-Controller serial, which Nexus sets to the first 20 bytes of the Oxide
// disk name. Propolis emulates NVMe 1.0, whose Identify-Namespace carries no eui64, nguid or uuid, so
// /dev/disk/by-id/nvme-eui.* and nvme-uuid.* do not exist, and the by-id names that do exist encode
// the disk name through udev's escaping rules, which is an implementation detail Oxide reserves the
// right to change. The serial is not: it is what the guest is guaranteed to see.
//
// Every disk is matched positively and anything that does not match is left strictly alone, which is
// how the boot disk is excluded without ever being identified. SYMLINK+= only adds a name; it never
// renames or replaces a device node, so a rule cannot take a disk away from anything else.
//
// ENV{DEVTYPE}=="disk" keeps the rule off partitions, whose KERNEL name also matches nvme*n*.
func UdevRules(plan *storage.Plan) (string, error) {
	var out strings.Builder
	out.WriteString(
		"# Generated by karpenter-provider-oxide. Names this instance's data disks by the NVMe\n" +
			"# serial Nexus derives from the Oxide disk name, which is the only deterministic handle\n" +
			"# the guest has: device numbering need not match the order the disks were created in.\n",
	)
	for _, set := range plan.Sets {
		for _, disk := range set.Disks {
			if err := checkSerial(set.Name, disk.Ordinal, disk.Serial); err != nil {
				return "", err
			}
			fmt.Fprintf(&out,
				`SUBSYSTEM=="block", ENV{DEVTYPE}=="disk", KERNEL=="nvme*n*", `+
					`ATTRS{serial}=="%s", SYMLINK+="%s"`+"\n",
				disk.Serial,
				strings.TrimPrefix(DevicePath(set.Name, disk.Ordinal), "/dev/"),
			)
		}
	}
	return out.String(), nil
}

// FstabBlock renders the /etc/fstab lines for the disks the guest mounts, which the install step
// splices into /etc/fstab between its markers.
//
// Keyed on the udev name rather than on a filesystem UUID. A UUID is not knowable when this is
// rendered -- mkfs writes it on the node, on a disk that may not exist yet -- which is what forced
// the previous design to rewrite fstab from a script on every boot. The objection to keying on a
// device path does not apply to a path we define ourselves in our own rule.
//
// Returns the empty string for a plan whose disks are all raw block, which are linked and never
// mounted.
func FstabBlock(plan *storage.Plan) (string, error) {
	var out strings.Builder
	for _, set := range plan.Sets {
		for _, disk := range set.Disks {
			if disk.MountPoint == "" {
				continue
			}
			options := mountOptions
			if disk.ReadOnly {
				// The rack refuses writes to a read-only attachment whatever the mount says, so a
				// default rw mount would simply fail. Known here rather than probed on the node,
				// because it is a property of the attachment the launch asked for.
				options += ",ro"
			}
			fields := []string{
				DevicePath(set.Name, disk.Ordinal),
				disk.MountPoint,
				fstabType(disk.Filesystem),
				options,
				"0",
				"0",
			}
			for _, field := range fields {
				if err := checkField(set.Name, disk.Ordinal, field); err != nil {
					return "", err
				}
			}
			out.WriteString(strings.Join(fields, " "))
			out.WriteString("\n")
		}
	}
	return out.String(), nil
}

// Config renders the table of disks the node-side script reads.
//
// It carries only what is left after udev and systemd have taken their halves: which device, what to
// format it as, where it will be mounted so a populated mount point can be seeded and a fresh
// filesystem relabelled, and where a raw block device is linked. Nothing in it is needed to find a
// disk or to mount one.
//
// Tab separated rather than JSON or YAML because it is parsed by a shell "read -r" loop on a node
// that is not guaranteed to have jq. Exported so a test can assert that what the script reads is
// what the plan says.
func Config(plan *storage.Plan) (string, error) {
	var out strings.Builder
	out.WriteString(configHeader)
	for _, set := range plan.Sets {
		for _, disk := range set.Disks {
			fields := []string{
				DevicePath(set.Name, disk.Ordinal),
				filesystemField(disk.Filesystem),
				orNone(disk.MountPoint),
				orNone(disk.BlockLink),
			}
			for _, field := range fields {
				if err := checkField(set.Name, disk.Ordinal, field); err != nil {
					return "", err
				}
			}
			out.WriteString(strings.Join(fields, "\t"))
			out.WriteString("\n")
		}
	}
	return out.String(), nil
}

// configHeader documents the table for whoever reads it on a node.
const configHeader = `# Generated by karpenter-provider-oxide. Read by ` + ScriptPath + `, once per boot.
# Editing it does not change the node: the OxideNodeClass is the source, and a change there
# relaunches the node. Fields are tab separated:
#
#   device	filesystem	mount	link
#
# filesystem is ext4 or xfs for a disk the node formats, ` + fieldRawBlock + ` for a raw block device
# that is only symlinked, or ` + fieldNone + ` for a disk created from an image or a snapshot, which
# arrives already carrying one. mount and link are absolute paths, or ` + fieldNone + ` where they do
# not apply. The devices are named by the udev rules installed alongside this file.
`

// filesystemField is what the script should do with a disk: format it, link it, or leave what is
// already on it alone.
func filesystemField(filesystem string) string {
	switch filesystem {
	case "":
		// Created from an image or a snapshot, so it already carries a filesystem.
		return fieldNone
	case v1alpha1.FilesystemNone:
		return fieldRawBlock
	default:
		return filesystem
	}
}

// fstabType is the filesystem an fstab entry declares.
func fstabType(filesystem string) string {
	if filesystem == "" {
		return fstabAuto
	}
	return filesystem
}

func orNone(value string) string {
	if value == "" {
		return fieldNone
	}
	return value
}

// checkField refuses a value carrying whitespace, a quote, a backslash or a newline rather than
// escaping it. A tab or a newline would break the table's framing, a space would break the fstab
// entry beside it, and a quote or a backslash would break the shell literals the installer renders.
// Every one of these is already refused by the CRD's patterns and again by the storage planner, so
// reaching this is the third guard rather than the first.
func checkField(setName string, ordinal int32, value string) error {
	if value == "" {
		return fmt.Errorf(
			"disk: diskSet %q disk %d has an empty field, which the table cannot represent",
			setName, ordinal,
		)
	}
	if strings.ContainsAny(value, " \t\n\r'\"\\") {
		return fmt.Errorf(
			"disk: diskSet %q disk %d has the value %q, which carries whitespace, a quote or a "+
				"backslash and cannot be rendered into the node's disk configuration",
			setName, ordinal, value,
		)
	}
	return nil
}

// checkSerial refuses a serial that would not match literally in a udev rule.
//
// udev compares ATTRS{} values with fnmatch, so a metacharacter would silently turn the serial into
// a pattern and could match a disk the nodeclass never named -- including, in the worst case, the
// boot disk. Karpenter's disk names cannot contain one, which is exactly why it is worth asserting.
func checkSerial(setName string, ordinal int32, serial string) error {
	if err := checkField(setName, ordinal, serial); err != nil {
		return err
	}
	if strings.ContainsAny(serial, "*?[]!") {
		return fmt.Errorf(
			"disk: diskSet %q disk %d has the serial %q, which contains an fnmatch metacharacter "+
				"and could not be matched literally by a udev rule",
			setName, ordinal, serial,
		)
	}
	return nil
}
